const I18N = {
  lang: 'mn', listeners: new Set(), canvases: new Map(),
  text(value, lang = this.lang) {
    const source = value == null ? '' : String(value);
    if (lang !== 'en') return source;
    if (Object.hasOwn(EN_TEXT, source)) return EN_TEXT[source];
    // Keep changing scores, times, answer letters and decorated labels translatable.
    let m;
    if ((m = source.match(/^Түлээ (\d+) \/ (\d+)$/))) return `Firewood ${m[1]} / ${m[2]}`;
    if ((m = source.match(/^−(\d+)( сек|с)$/))) return `−${m[1]}${m[2] === 'с' ? 's' : ' sec'}`;
    if ((m = source.match(/^Үлдсэн цаг: (\d+) сек\. Үлдсэн секунд бүр \+2 гэрэл\.$/))) return `Time left: ${m[1]} sec. Each remaining second earns +2 light.`;
    if ((m = source.match(/^Үлдсэн (\d+) сек × 2$/))) return `${m[1]} sec left × 2`;
    if ((m = source.match(/^Асуулт (\d+) \/ (\d+)$/))) return `Question ${m[1]} / ${m[2]}`;
    if ((m = source.match(/^Гэрлийн оноо: (\d+)$/))) return `Light score: ${m[1]}`;
    if ((m = source.match(/^([АБВ])\)  (.*)$/s))) return `${'ABC'['АБВ'.indexOf(m[1])]})  ${this.text(m[2], lang)}`;
    if ((m = source.match(/^Зөв хариулт: ([АБВ])\. (.*)$/s))) return `Correct answer: ${'ABC'['АБВ'.indexOf(m[1])]}. ${this.text(m[2], lang)}`;
    if ((m = source.match(/^Зөв! (.*)$/s))) return `Correct! ${this.text(m[1], lang)}`;
    if ((m = source.match(/^Зөв хайрцаг нь: (.*)$/s))) return `Correct box: ${this.text(m[1], lang)}`;
    if ((m = source.match(/^(✓  |\d+\. )(.*)$/s))) return m[1] + this.text(m[2], lang);
    return source;
  },
  onChange(callback) { this.listeners.add(callback); return () => this.listeners.delete(callback); },
  set(lang) {
    if (!['mn', 'en'].includes(lang) || lang === this.lang) return false;
    this.lang = lang;
    try { localStorage.setItem('nyagtaa_language', lang); } catch (e) { /* Storage may be disabled. */ }
    this.syncDOM();
    this.canvases.forEach(redraw => redraw());
    this.listeners.forEach(refresh => refresh());
    return true;
  },
  // Only texts created by our UI helper are bound; Phaser's prototypes are untouched.
  bindText(t, source, options = {}) {
    const nativeSet = t.setText;
    const refresh = () => {
      nativeSet.call(t, this.text(source));
      if (options.maxWidth || options.maxHeight) {
        t.setFontSize(options.size);
        const ratio = Math.min(1, options.maxWidth ? options.maxWidth / Math.max(1, t.width) : 1,
          options.maxHeight ? options.maxHeight / Math.max(1, t.height) : 1);
        if (ratio < 1) t.setFontSize(Math.floor(options.size * ratio));
      }
      t.emit('localized');
      return t;
    };
    t.setText = value => { source = value; return refresh(); };
    const unsubscribe = this.onChange(refresh);
    t.once('destroy', unsubscribe);
    refresh();
    return t;
  },
  syncDOM() {
    document.documentElement.lang = this.lang;
    document.title = this.text('Нягтаа: Факт гаригийн аян');
    document.querySelectorAll('[data-i18n]').forEach(node => { node.textContent = this.text(node.dataset.i18n); });
    const controls = document.getElementById('language-controls');
    controls.setAttribute('aria-label', this.text('Хэл'));
    controls.querySelectorAll('[data-language]').forEach(button => {
      button.setAttribute('aria-pressed', String(button.dataset.language === this.lang));
    });
  },
  init() {
    try { if (localStorage.getItem('nyagtaa_language') === 'en') this.lang = 'en'; } catch (e) { }
    const controls = document.getElementById('language-controls');
    controls.querySelectorAll('[data-language]').forEach(button => button.addEventListener('click', event => {
      event.stopPropagation(); this.set(button.dataset.language);
    }));
    // Space/Enter on a language button must not also advance dialogue or chop wood.
    controls.addEventListener('keydown', event => event.stopPropagation());
    controls.addEventListener('keyup', event => event.stopPropagation());
    this.syncDOM();
  },
};
I18N.init();
